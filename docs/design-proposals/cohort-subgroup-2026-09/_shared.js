// 身份称谓派生 (镜像 app/core/member_identity.py _RULES)
window.memberStatus = function (g) {
  g = (g || '').trim()
  if (!g) return '成员'
  const rules = [
    [['教授','副教授','讲师','老师','教师','研究员','副研究员','辅导员','导师'], '导师'],
    [['博士后','博后'], '博士后'],
    [['博'], '博士'],
    [['研','硕'], '硕士'],
    [['本','大一','大二','大三','大四'], '本科生'],
    [['毕业','校友'], '校友'],
  ]
  for (const [kw, st] of rules) if (kw.some(k => g.includes(k))) return st
  return g
}
